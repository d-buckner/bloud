package main

import (
	"fmt"
	"os"
	"strings"

	"codeberg.org/d-buckner/bloud/cli/portspec"
)

// portsMode is what a `bloud ports` run does with the derived list.
type portsMode int

const (
	portsPrint portsMode = iota
	portsWrite
	portsCheck
	portsHelp
)

// The three documents that carry the debug-port list. Each one is a different
// rendering of the same derived answer, which is the whole point: the QEMU
// launch arguments, the two VM specs, and the port table in AGENTS.md used to
// be four hand-written copies of a list, and two of them had already drifted
// from the catalog that owns the numbers.
const (
	portsYAMLBeginMarker  = "# BEGIN GENERATED DEBUG PORT FORWARDS"
	portsYAMLEndMarker    = "# END GENERATED DEBUG PORT FORWARDS"
	portsTableBeginMarker = "<!-- BEGIN GENERATED DEBUG PORTS -->"
	portsTableEndMarker   = "<!-- END GENERATED DEBUG PORTS -->"
)

// portsGeneratedByYAML and portsGeneratedByMarkdown are the in-block
// provenance notes. A YAML file cannot carry an HTML comment, so each shape
// states the same thing in its own comment syntax.
const (
	portsGeneratedByYAML     = "# Generated by `./bloud ports --write` from `apps/*/metadata.yaml`. Do not edit by hand."
	portsGeneratedByMarkdown = "<!-- Generated by `./bloud ports --write` from `apps/*/metadata.yaml`. Do not edit by hand. -->"
)

// portsTarget is one document this command owns a block in.
type portsTarget struct {
	path  string
	block generatedBlock
	kind  portspec.Kind
	// render turns the derived list into the block, markers included.
	render func(portspec.List, generatedBlock) string
}

func portsTargets() []portsTarget {
	yamlBlock := generatedBlock{Begin: portsYAMLBeginMarker, End: portsYAMLEndMarker, Label: "debug port forwards"}
	return []portsTarget{
		{
			path:   "dev/lima.yaml",
			block:  yamlBlock,
			kind:   portspec.KindLima,
			render: renderPortsYAML,
		},
		{
			path:   "dev/qemu.yaml",
			block:  yamlBlock,
			kind:   portspec.KindQEMU,
			render: renderPortsYAML,
		},
		{
			path: "AGENTS.md",
			block: generatedBlock{
				Begin: portsTableBeginMarker,
				End:   portsTableEndMarker,
				Label: "debug port table",
			},
			kind:   portspec.KindLima,
			render: renderPortsTable,
		},
	}
}

// renderPortsYAML writes the list in the shape both VM specs use: a
// `portForwards:` mapping, with `hostPort` only where the host port differs
// from the guest port.
func renderPortsYAML(list portspec.List, block generatedBlock) string {
	var sb strings.Builder
	sb.WriteString(block.Begin + "\n")
	sb.WriteString(portsGeneratedByYAML + "\n")
	sb.WriteString("portForwards:\n")
	for _, f := range list.Forwards {
		fmt.Fprintf(&sb, "  - guestPort: %-4d # %s\n", f.Guest, f.Label)
		if f.Host != f.Guest {
			fmt.Fprintf(&sb, "    hostPort: %d\n", f.Host)
		}
	}
	sb.WriteString(renderPortsSkipped(list, "# ", "\n# "))
	sb.WriteString(block.End + "\n")
	return sb.String()
}

// renderPortsTable writes the AGENTS.md table. The two ports a person actually
// dials carry prose that this command cannot generate, and that prose stays in
// the hand-written text above the table; the table itself is the flat list.
func renderPortsTable(list portspec.List, block generatedBlock) string {
	var sb strings.Builder
	sb.WriteString(block.Begin + "\n")
	sb.WriteString(portsGeneratedByMarkdown + "\n")
	sb.WriteString("| Port | What | Audience |\n")
	sb.WriteString("| --- | --- | --- |\n")
	for _, f := range list.Forwards {
		port := fmt.Sprint(f.Guest)
		if f.Host != f.Guest {
			port = fmt.Sprintf("%d on host %d", f.Guest, f.Host)
		}
		fmt.Fprintf(&sb, "| %s | %s | %s |\n", port, f.Label, f.Audience)
	}
	sb.WriteString(renderPortsSkipped(list, "", "; "))
	sb.WriteString(block.End + "\n")
	return sb.String()
}

// renderPortsSkipped lists the declared ports that get no forward. Silence here
// is how the old copies went wrong, so each one is named with its reason.
func renderPortsSkipped(list portspec.List, prefix, sep string) string {
	if len(list.Skipped) == 0 {
		return ""
	}
	names := make([]string, 0, len(list.Skipped))
	for _, s := range list.Skipped {
		names = append(names, fmt.Sprintf("%d (%s: %s)", s.Guest, s.App, s.Reason))
	}
	return prefix + "Not forwarded: " + strings.Join(names, sep) + "\n"
}

func cmdPorts(args []string) int {
	mode, target := parsePortsArgs(args)
	if mode == portsHelp {
		printPortsUsage()
		return 0
	}

	root, err := getProjectRoot()
	if err != nil {
		errorf("Could not find project root: %v", err)
		return 1
	}
	targets := portsTargets()
	if target != "" {
		targets, err = selectPortsTarget(targets, target)
		if err != nil {
			errorf("%v", err)
			return 1
		}
	}

	appsDir := root + "/apps"
	failed := false
	for _, t := range targets {
		list, err := portspec.Derive(appsDir, t.kind)
		if err != nil {
			errorf("Failed to derive the debug port list: %v", err)
			return 1
		}
		generated := t.render(list, t.block)
		switch mode {
		case portsWrite:
			if !writePortsBlock(root, t, generated) {
				failed = true
			}
		case portsCheck:
			if !checkPortsBlock(root, t, generated) {
				failed = true
			}
		default:
			fmt.Print(generated)
		}
	}
	if failed {
		return 1
	}
	return 0
}

// selectPortsTarget narrows the run to one document. Only the documents this
// command knows how to render are accepted: a path it guesses at would write a
// block into a file that has no markers for it.
func selectPortsTarget(targets []portsTarget, target string) ([]portsTarget, error) {
	for _, t := range targets {
		if t.path == target {
			return []portsTarget{t}, nil
		}
	}
	known := make([]string, 0, len(targets))
	for _, t := range targets {
		known = append(known, t.path)
	}
	return nil, fmt.Errorf("--target must be one of: %s", strings.Join(known, ", "))
}

func parsePortsArgs(args []string) (portsMode, string) {
	mode := portsPrint
	target := ""
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--write":
			mode = portsWrite
		case "--check":
			mode = portsCheck
		case "--help", "-h":
			return portsHelp, ""
		case "--target":
			if i+1 >= len(args) {
				errorf("--target needs a path (usage: bloud ports [--write | --check] [--target FILE])")
				return portsHelp, ""
			}
			i++
			target = args[i]
		default:
			errorf("unknown flag %q (usage: bloud ports [--write | --check] [--target FILE])", args[i])
			return portsHelp, ""
		}
	}
	return mode, target
}

func writePortsBlock(root string, t portsTarget, generated string) bool {
	path := docTargetPath(root, t.path)
	content, err := os.ReadFile(path)
	if err != nil {
		errorf("%s: %v", relOrAbs(root, path), err)
		return false
	}
	if !t.block.Present(string(content)) {
		errorf("%s", t.block.missingBlockMessage(relOrAbs(root, path)))
		return false
	}
	updated, ok := t.block.Splice(string(content), generated)
	if !ok {
		errorf("%s: could not replace the block", relOrAbs(root, path))
		return false
	}
	if updated == string(content) {
		fmt.Printf("%s: up to date\n", relOrAbs(root, path))
		return true
	}
	if err := os.WriteFile(path, []byte(updated), 0o644); err != nil {
		errorf("%s: %v", relOrAbs(root, path), err)
		return false
	}
	fmt.Printf("%s: refreshed\n", relOrAbs(root, path))
	return true
}

func checkPortsBlock(root string, t portsTarget, generated string) bool {
	path := docTargetPath(root, t.path)
	content, err := os.ReadFile(path)
	if err != nil {
		errorf("%s: %v", relOrAbs(root, path), err)
		return false
	}
	existing, ok := t.block.Extract(string(content))
	if !ok {
		errorf("%s", t.block.missingBlockMessage(relOrAbs(root, path)))
		return false
	}
	if t.block.Same(existing, generated) {
		return true
	}
	errorf("%s: the %s block is not what the catalog produces", relOrAbs(root, path), t.block.Label)
	t.block.ReportDifference(existing, generated)
	return false
}

func printPortsUsage() {
	fmt.Println(strings.Join([]string{
		"Usage: bloud ports [--write | --check] [--target FILE]",
		"",
		"Derive the debug port forwards from apps/*/metadata.yaml.",
		"",
		"The catalog owns which ports exist. This command writes that answer into",
		"the two VM specs and the AGENTS.md table, so no copy of the list can drift",
		"from the apps it describes.",
		"",
		"  (no flag)     Print the derived list for each target",
		"  --write       Replace the generated block in every target",
		"  --check       Exit 1 when a target is not what the catalog produces",
		"  --target FILE Narrow the run to one target",
	}, "\n"))
}
