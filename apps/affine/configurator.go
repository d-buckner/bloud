// renderConfigFile renders the AFFiNE config.json. Only keys that override
// defaults are set; AFFiNE merges the file over its built-in defaults.
func renderConfigFile(externalURL string, oidc *configurator.OIDCOutput) (string, error) {
	cfg := map[string]any{
		"server": map[string]any{
			"externalUrl": externalURL,
		},
		// AFFiNE's first-open flow creates a local "Demo Workspace" (nanoid)
		// when this flag is on, and the operator lands in that demo instead of
		// the server workspace Bloud created and wired with the AI endpoint. A
		// local workspace is invisible to Bloud's GraphQL API, so the BYOK
		// profile and the AI chat would live in different workspaces and every
		// chat would fail with `no_compatible_target`. Disabling the guest demo
		// makes the operator's first workspace the server one Bloud owns.
		"flags": map[string]any{
			"allowGuestDemoWorkspace": false,
		},
		// The invite quota is the one thing standing between Bloud and adding its
		// own users to its own workspace, and on self-host it is set to zero: the
		// admission check answers `limit: 0, reason: 'quota_subject'` and every
		// `inviteMembers` call is a 429. The guard exists to stop anonymous
		// signups spamming invites to strangers on AFFiNE's hosted infrastructure.
		// Neither applies here: the inviter is Bloud's own bootstrap admin, the
		// invitees are the accounts the operator created in Bloud's identity
		// provider, and the server is a home box with no mail transport. Shadow
		// mode keeps the accounting and drops the rejection, which is the whole
		// point of the flag rather than a bypass of it.
		"auth": map[string]any{
			"inviteQuotaShadowMode": true,
		},
		// The MCP server lives under AFFiNE's copilot module and the flag
		// defaults off, so without this every credential mint and every MCP
		// request answers "Copilot is disabled."
		//
		// The byok block is the policy half of the inference wiring: AFFiNE
		// gates an OpenAI-compatible endpoint behind an explicit server
		// opt-in, and Bloud's gateway is one. `allowCustomEndpoint` makes the
		// custom-endpoint mode "enabled" (the Rust policy returns
		// "disabled" on self-host without it), and `allowPrivateEndpoint`
		// admits a container-network address, which `apps-litellm` /
		// `apps-ollama` are. A public endpoint needs neither, but the private
		// case is the one Bloud ships, so the flag is on. The trade-off is
		// AFFiNE's own warning: every workspace admin may then point AFFiNE
		// at a private-network service. Acceptable for a single-tenant home
		// server, and it is what makes the endpoint reachable at all.
		"copilot": map[string]any{
			"enabled": true,
			"byok": map[string]any{
				"enabled":              true,
				"allowCustomEndpoint":  true,
				"allowPrivateEndpoint": true,
			},
		},
	}
	if oidc != nil {
		cfg["oauth"] = map[string]any{
			"providers": map[string]any{
				"oidc": map[string]any{
					"clientId":            oidc.ClientID,
					"clientSecret":        oidc.ClientSecret,
					"issuer":              oidc.IssuerURL,
					"allowPrivateNetwork": true,
				},
			},
		}
	}
	// json.Marshal sorts map keys alphabetically, so the rendering is
	// deterministic: an unchanged config never churns the file across
	// reconciliation cycles.
	out, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return "", fmt.Errorf("rendering config file: %w", err)
	}
	return string(out) + "\n", nil
}
