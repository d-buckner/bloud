package navidromemcp

import (
	"fmt"
	"strings"

	"codeberg.org/d-buckner/bloud/pkg/bindings"
)

// renderEnvFile renders the env file the container is created from: one
// `KEY=value` line per setting. Only values that resolved are written, so an
// unresolved provider is an absent variable rather than an empty one, and the
// server reads those two differently: an absent NAVIDROME_URL is a configuration
// error it reports, an empty one is a destination it will try to dial.
//
// The second return value names the first key whose value could not be rendered,
// or "" when everything fit. The caller logs it, and never logs the value: one of
// these keys is a password.
func renderEnvFile(provider bindings.MediaServerBinding, hasProvider bool, bearer string) (string, string) {
	var b strings.Builder
	b.WriteString("# Generated by Bloud; rewritten on every reconciliation.\n")

	settings := make([][2]string, 0, 4)
	if hasProvider {
		if provider.BaseURL != "" {
			settings = append(settings, [2]string{envNavidromeURL, provider.BaseURL})
		}
		if provider.AdminUsername != "" {
			settings = append(settings, [2]string{envNavidromeUser, provider.AdminUsername})
		}
		if provider.AdminPassword.Published() {
			settings = append(settings, [2]string{envNavidromePass, provider.AdminPassword.String()})
		} else {
			// Recorded in the file because it is the state the container starts in,
			// and because "the provider has not published one yet" is a different
			// fact from "this app was configured with no password".
			b.WriteString("# " + envNavidromePass + " absent: the music server has not published a credential yet\n")
		}
	}
	if bearer != "" {
		settings = append(settings, [2]string{envAuthToken, bearer})
	}

	omitted := ""
	for _, kv := range settings {
		value, ok := envValue(kv[1])
		if !ok {
			if omitted == "" {
				omitted = kv[0]
			}
			// The value is never echoed: one of these keys is a password.
			fmt.Fprintf(&b, "# %s omitted: its value cannot sit on one env-file line\n", kv[0])
			continue
		}
		fmt.Fprintf(&b, "%s=%s\n", kv[0], value)
	}
	return b.String(), omitted
}

// envValue reports whether a value can be written to the env file, and returns it
// rendered.
//
// The reader is the runtime's env-file parser: it trims the line, cuts on the
// first `=`, then strips one layer of matching surrounding quotes. So a value
// written bare comes back exactly as it went in unless it carries a line break,
// arrives with padding the trim would eat, or happens to begin and end with the
// same quote character, which the parser would strip as that one layer. Anything
// else, an apostrophe in the middle of a password included, needs no quoting, and
// adding quotes would only add a second set of rules the writer and the reader
// could disagree about.
//
// A value that cannot be rendered is left out of the file rather than escaped into
// something else. An app that starts with no credential and says so beats one that
// starts with a credential that fails on every call.
func envValue(value string) (string, bool) {
	if value == "" || value != strings.TrimSpace(value) || strings.ContainsAny(value, "\r\n") {
		return "", false
	}
	if len(value) >= 2 {
		first := value[0]
		last := value[len(value)-1]
		if (first == '\'' || first == '"') && first == last {
			return "", false
		}
	}
	return value, true
}
